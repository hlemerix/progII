destino = "Grecia"
ticket = "playa"

# isalpha: Verifica si son solo letras
print("¿El destino son solo letras?")
print(destino.isalpha())

# isupper: Verifica si está en mayúsculas
print("¿El ticket está en mayúsculas?")
print(ticket.isupper())

# isalnum: Verifica si tiene letras y números
print("¿El ticket es alfanumerico?")
print(ticket.isalnum())